"""Export current rule constants for UI reference checks without running analysis."""
import ast
import hashlib
import json
from pathlib import Path
import argparse

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--backend', type=Path, default=Path('../automatic-chess-annotator'))
args = parser.parse_args()
rules = args.backend / 'app/core/commentary/rules'
tree = ast.parse((rules / 'constants.py').read_text(encoding='utf-8-sig'))
values = {node.target.id: ast.literal_eval(node.value) for node in tree.body
          if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)
          and node.target.id in {'THRESHOLDS', 'COUNT_CLAIM_CP'}}
files = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(rules.glob('*.py'))}
revision = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
output = Path(__file__).resolve().parents[1] / 'src/helpers/ruleReference.generated.ts'
output.write_text('// Generated by scripts/export-rule-reference.py. Current reference, not historical trigger provenance.\n'
                  + f'export const RULE_REFERENCE_REVISION = {json.dumps(revision)}\n'
                  + f'export const RULE_THRESHOLDS = {json.dumps(values["THRESHOLDS"], indent=2)} as const\n'
                  + f'export const COUNT_CLAIM_WEIGHTS = {json.dumps(values["COUNT_CLAIM_CP"], indent=2)} as const\n', encoding='utf-8')
print(output)
